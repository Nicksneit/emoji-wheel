function ewT(lang, key) {
  const table = EW_I18N[lang] || EW_I18N.en;
  return table[key] ?? EW_I18N.en[key] ?? key;
}

function ewDetectLang() {
  const l = (navigator.language || "en").toLowerCase();
  if (l.startsWith("zh")) return "zh";
  const base = l.split("-")[0];
  return EW_I18N[base] ? base : "en";
}
